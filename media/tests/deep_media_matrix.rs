fn test_html(idx: usize) -> String {
    format!(
        "<html><head><title>T{idx}</title><meta name=\"description\" content=\"D{idx}\"></head><body><main><h1>Title {idx}</h1><p>This is paragraph {idx} with enough words to parse readability and markdown conversion output in deterministic form.</p></main></body></html>"
    )
}

#[test]
fn link_extract_matrix_smoke() {
    let analyzer = LinkAnalyzer::new(LinkConfig::default()).expect("analyzer");
    for idx in 0..200 {
        let html = test_html(idx);
        let out = analyzer
            .extract_from_html(&format!("https://example.com/{idx}"), &html)
            .expect("extract");
        assert!(out.markdown.contains("Title"));
        assert!(out.text_length > 10);
        let expected = format!("T{idx}");
        assert_eq!(out.title.as_deref(), Some(expected.as_str()));
    }
}

#[cfg(feature = "tts")]
#[test]
fn tts_config_matrix_smoke() {
    let mut client = TtsClient::new(TtsConfig::default());
    for idx in 0..120 {
        client.set_voice_for_agent(
            format!("agent-{idx}"),
            VoiceConfig {
                provider: if idx % 2 == 0 {
                    TtsProvider::OpenAi
                } else {
                    TtsProvider::ElevenLabs
                },
                voice_id: if idx % 2 == 0 {
                    "alloy".to_string()
                } else {
                    format!("voice-{idx}")
                },
                speed: 1.0,
                stability: 0.5,
                similarity_boost: 0.5,
                style: 0.2,
                use_speaker_boost: false,
            },
        );
    }
    let voices = client.list_agent_voices();
    assert!(voices.len() >= 120);
    assert_eq!(OutputFormat::Mp3.content_type(), "audio/mpeg");
}

