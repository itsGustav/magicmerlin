fn build_ctx() -> ToolContext {
    let temp = tempfile::tempdir().expect("temp");
    let scope = magicmerlin_config::PathScope::dev();
    let state_paths = magicmerlin_config::StatePaths::new(scope).expect("state paths");
    ToolContext {
        agent_name: "matrix-agent".to_string(),
        workspace_dir: temp.path().to_path_buf(),
        state_paths,
        config: magicmerlin_config::Config::default(),
        delivery: None,
        process_manager: ProcessManager::new(),
        node_configs: vec![],
        browser_manager: None,
        canvas_server: None,
        tts_client: None,
        understanding_client: None,
    }
}

#[tokio::test]
async fn registry_baseline_matrix() {
    let mut registry = ToolRegistry::new();
    register_default_tools(&mut registry);
    let names = registry.names();
    assert!(names.contains(&"exec".to_string()));
    assert!(names.contains(&"nodes".to_string()));
}

